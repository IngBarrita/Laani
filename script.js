// Cada grupo tiene su propia sección. Las tarjetas se crean una sola vez.
const groupContent = document.getElementById("group-content");
const tabs = document.querySelectorAll(".tab[data-group]");
const groupSections = {};

function createGroupSection(group) {
  const section = document.createElement("div");
  section.className = "group-section";
  section.dataset.group = group;
  section.style.width = "100%";
  section.style.gridColumn = "1 / -1";

  const poems = calaveritas[group] || [];
  if (poems.length === 0) {
    const empty = document.createElement("div");
    empty.className = "empty-state";
    const title = document.createElement("strong");
    title.textContent = `Próximamente: calaveritas de ${group}`;
    const message = document.createElement("span");
    message.textContent = "El docente agregará aquí las calaveritas de este grupo.";
    empty.append(title, message);
    section.appendChild(empty);
  } else {
    poems.forEach((poem) => {
      const card = document.createElement("article");
      card.className = "poem-card";
      const title = document.createElement("h3");
      title.textContent = poem.titulo || "Calaverita sin título";
      const meta = document.createElement("p");
      meta.className = "poem-meta";
      meta.textContent = `Grupo ${group} · ${poem.autor || "Autor no indicado"}`;
      card.append(title, meta);
      (poem.estrofas || []).forEach((stanza, index) => {
        const paragraph = document.createElement("p");
        paragraph.className = "poem-stanza";
        paragraph.textContent = stanza;
        paragraph.setAttribute("aria-label", `Estrofa ${index + 1}`);
        card.appendChild(paragraph);
      });
      section.appendChild(card);
    });
  }
  return section;
}

if (groupContent) {
  Object.keys(calaveritas).forEach((group) => {
    const section = createGroupSection(group);
    groupSections[group] = section;
    groupContent.appendChild(section);
  });

  function showGroup(group) {
    if (!groupSections[group]) return;
    Object.entries(groupSections).forEach(([name, section]) => {
      // display evita que una regla CSS sobreescriba el atributo hidden.
      section.style.display = name === group ? "block" : "none";
    });
    tabs.forEach((tab) => {
      const selected = tab.dataset.group === group;
      tab.classList.toggle("active", selected);
      tab.setAttribute("aria-pressed", String(selected));
    });
  }

  tabs.forEach((tab) => {
    tab.addEventListener("click", () => showGroup(tab.dataset.group));
  });
  showGroup("1F");
}
